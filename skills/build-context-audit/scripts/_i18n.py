def lang_from_locale(value: str) -> str:
    """Korean locales (``ko``, ``ko_KR.UTF-8``) give ``ko``; everything else gives ``en``."""
    return "ko" if value.strip().lower().startswith("ko") else "en"


def resolve_lang(cli_value: str | None, env: Mapping[str, str]) -> str:
    """``--lang`` > ``BUILD_CONTEXT_AUDIT_LANG`` > ``LC_ALL`` > ``LC_MESSAGES`` > ``LANG``."""
    if cli_value in LANGS:
        return cli_value  # type: ignore[return-value]
    for name in (ENV_VAR, "LC_ALL", "LC_MESSAGES", "LANG"):
        value = env.get(name, "")
        if value.strip():
            return lang_from_locale(value)
    return "en"


def t(lang: str, key: str, **kwargs: object) -> str:
    """Look up ``key`` in ``lang`` (falling back to English) and fill the placeholders."""
    table = MESSAGES.get(lang) or MESSAGES["en"]
    template = table.get(key) or MESSAGES["en"][key]
    return template.format(**kwargs) if kwargs else template


def count_files(lang: str, n: int) -> str:
    """``1 file`` / ``3 files`` in English, ``3개`` in Korean."""
    if lang == "ko":
        return f"{n}개"
    return f"{n} file" if n == 1 else f"{n} files"
